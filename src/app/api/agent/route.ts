import { createAgentResponse } from "@/lib/agent/run-agent";

export const maxDuration = 60;

export async function POST(req: Request) {
  let body: unknown;
  try {
    body = await req.json();
  } catch {
    return Response.json({ error: "Invalid JSON" }, { status: 400 });
  }
  return createAgentResponse(body);
}
